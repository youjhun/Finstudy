def expand_explanation(old_text):
    """짧은 해설을 긴 해설로 확장"""
    return EXPANDED_EXPLANATIONS.get(old_text, old_text)

def main():
    # curriculum-data.ts 읽기
    with open('/home/ubuntu/finstudy-mobile/lib/curriculum-data.ts', 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 모든 explanation 필드 찾기 및 확장
    for old_text, new_text in EXPANDED_EXPLANATIONS.items():
        # 정확한 문자열 매칭
        pattern = f"explanation: '{re.escape(old_text)}'"
        replacement = f"explanation: '{new_text}'"
        content = content.replace(pattern, replacement)
    
    # 수정된 내용 저장
    with open('/home/ubuntu/finstudy-mobile/lib/curriculum-data.ts', 'w', encoding='utf-8') as f:
        f.write(content)
    
    print("✅ 해설 확장 완료!")
    print(f"   - 확장된 해설: {len(EXPANDED_EXPLANATIONS)}개")

if __name__ == '__main__':
    main()
