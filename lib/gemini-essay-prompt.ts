/**
 * 서술형 문제를 포함한 Gemini 프롬프트 생성
 */

export function buildArticleProcessingPrompt(articlesText: string, articleCount: number): string {
  return `당신은 경제 교육 전문가이자 시험 출제 전문가입니다. 다음은 ${articleCount}개의 뉴스 기사 리스트입니다.
각 기사별로 [요약, 주요포인트 3-4개, 경제용어 3-5개, 카테고리, 퀴즈 10문제]를 생성해서 하나의 거대한 JSON 배열 형식으로 응답해주세요.

[기사 리스트]
${articlesText}

**경제용어 추출 시 필수 규칙:**
- 경제용어는 반드시 "재정경제부_시사경제용어 정보" 데이터베이스에 정확히 존재하는 용어만 추출합니다.
- 부분 매칭이 아닌 "정확한 용어명"으로만 추출합니다.
- 예: "실적" 검색 시 "실적 공사비" 같은 다른 용어를 추출하지 않습니다.
- 예: "고용" 검색 시 "고령자고용촉진장려금제도" 같은 다른 용어를 추출하지 않습니다.
- 기사에서 추출한 용어들을 먼저 정리한 후, 경제용어사전에 정확히 존재하는 것만 최종 선택합니다.
- 만약 기사의 용어가 경제용어사전에 없으면, 그 용어는 포함하지 않습니다.

**요구사항:**
1. 각 기사마다 정확히 10개의 퀴즈를 생성합니다.
2. 퀴즈 구성 및 난이도 (반드시 데이터에 포함):
   - 문제 1-2: 기사 내용 직접 이해 (난이도: "easy", 타입: "multiple-choice", 4개 선택지)
   - 문제 3-5: 기사 내용을 바탕으로 한 논리적 추론 (난이도: "medium", 타입: "multiple-choice", 4개 선택지)
   - 문제 6-8: 기사 내용의 경제적 파급효과 분석 (난이도: "hard", 타입: "multiple-choice", 4개 선택지)
   - 문제 9: 거시경제 관점에서의 종합 판단 (난이도: "hard", 타입: "multiple-choice", 4개 선택지)
   - 문제 10: 기사에 없는 내용을 논리적으로 유추하는 서술형 문제 (난이도: "hard", 타입: "essay", 선택지 없음)

3. 서술형 문제(문제 10) 요구사항:
   - 기사의 핵심 경제 흐름을 이해하고 거시적 관점에서 분석하는 능력을 평가
   - 기사에 직접 나오지 않는 내용이지만 논리적으로 유추 가능한 질문
   - 예시: 
     * "이 기사의 경제 흐름이 계속되면 향후 어떤 경제 지표에 영향을 미칠까?"
     * "정부가 이에 대응하기 위해 취할 수 있는 정책은 무엇일까?"
     * "이 현상이 국제 경제에 미칠 파급효과를 분석하시오."
   - 서술형 답변은 정오답이 아닌 논리성과 경제 개념 이해도를 평가하는 방식으로 진행
   - answer 필드는 포함하지 않음 (서술형이므로 정답이 없음)

4. 객관식 퀴즈(문제 1-9):
   - 각 퀴즈는 4개의 선택지를 가집니다.
   - 선택지는 모두 그럴듯해야 하며, 정답과 오답의 차이가 명확해야 합니다.
   - 각 퀴즈마다 정답 인덱스(0-3)와 해설을 포함합니다.
   - 해설은 최소 50자 이상, 최대 200자 이내여야 합니다.
   - 해설에는 왜 정답인지, 왜 다른 선택지는 틀렸는지 간결하게 설명해야 합니다.

5. 기타 요구사항:
   - 난이도는 "easy", "medium", "hard" 중 하나입니다 (반드시 문자열로).
   - 모든 해설은 프리미엄 콘텐츠입니다 (isPremium: true).
   - 요약은 3-4문장입니다.
   - 주요 포인트와 경제 용어는 배열 형식입니다.
   - 선택지는 모두 한국어로 작성하고, 비슷한 길이를 유지하세요.
   - 기사 내용을 절대 임의로 수정하지 마세요. 기사에 있는 사실만 사용하세요.
   - 카테고리는 다음 중 하나입니다:
     * "머니/재테크": 금리, 환율, 주식, 부동산, 가상자산 등 실제 자산 형성과 직결된 뉴스
     * "산업/트렌드": 반도체, AI, 모빌리티, K-콘텐츠 등 세상을 바꾸는 기업과 기술 뉴스
     * "갓생/라이프": 소비 트렌드, 연금, 세금(연말정산), 청약 등 사회 초년생 필수 상식
     * "글로벌 이슈": 미국 대선, 전쟁, 국제 유가 등 거시(Macro) 경제 흐름을 보여주는 뉴스
     * "기타": 위에 해당하지 않는 경제 뉴스

**응답 형식 (JSON 배열만 응답, 다른 텍스트는 포함하지 마세요):**
[
  {
    "title": "기사 제목",
    "summary": "3-4문장 요약",
    "category": "머니/재테크",
    "keyPoints": ["포인트1", "포인트2", "포인트3"],
    "terms": ["용어1", "용어2", "용어3"],
    "quiz": [
      {
        "question": "객관식 질문 텍스트",
        "choices": ["선택지1", "선택지2", "선택지3", "선택지4"],
        "answer": 0,
        "explanation": "50-200자 범위의 간결하고 명확한 해설",
        "difficulty": "easy",
        "type": "multiple-choice",
        "isPremium": true
      },
      {
        "question": "서술형 질문: 기사의 경제 흐름을 거시적 관점에서 분석하고, 향후 경제에 미칠 영향을 논리적으로 설명하시오.",
        "explanation": "논리성과 경제 개념 이해도를 평가하는 방식으로 진행되며, 정오답이 아닙니다.",
        "difficulty": "hard",
        "type": "essay",
        "isPremium": true
      }
    ]
  }
]`;
}
